"""
4 - * 与 ** 解包（unpacking）用法总览

一句话记住：
    *  拆「可迭代对象」   -> 列表 / 元组 / 集合 / 字符串 / 生成器 ...
    ** 拆「映射（字典）」  -> 拆出来是 键=值 这种关键字实参

它们出现在 4 个位置，含义各不相同：
    1) 函数调用时   f(*args)   f(**kwargs)      -> 把容器"摊开"传进去
    2) 函数定义时   def f(*args, **kwargs)      -> 把实参"收进"元组/字典
    3) 字面量里     [*a, *b]   {**d1, **d2}     -> 拼接
    4) 赋值时       a, *rest = ...              -> 扩展解包

运行：
    python "4-解包.py"
"""

from __future__ import annotations


def title(text: str) -> None:
    print("\n" + "=" * 70)
    print(text)
    print("=" * 70)


# ---------------------------------------------------------------------------
# 0. 最原始的起点：字典 .items() 本身是"可迭代的键值对"
# ---------------------------------------------------------------------------

d = {"x": "1", "y": "2"}
print("d.items()          ->", d.items())          # dict_items([('x', '1'), ('y', '2')])


# ---------------------------------------------------------------------------
# 1. 函数调用时解包：* 拆位置参数，** 拆关键字参数
# ---------------------------------------------------------------------------

def add3(a: int, b: int, c: int) -> int:
    return a + b + c


def show(**kwargs) -> None:
    print("   收到的关键字:", kwargs)


title("1. 调用时解包（摊开传参）")

nums = [1, 2, 3]
print("*nums       ->", add3(*nums))          # 等价于 add3(1, 2, 3)

nums_tuple = (4, 5, 6)
print("*tuple      ->", add3(*nums_tuple))

# 字典用 ** 拆成关键字实参（键名必须匹配函数形参名）
params = {"a": 7, "b": 8, "c": 9}
print("**params    ->", add3(**params))       # 等价于 add3(a=7, b=8, c=9)

# * 和 ** 可以混用，位置参数在前
print("混合        ->", add3(1, *[2], **{"c": 3}))

# 字符串、集合、生成器都能被 * 拆开
print("*'abc'      ->", add3(*"123"))          # 字符串拆成 '1' '2' '3'（这里能转 int）
print("*生成器     ->", add3(*(i for i in (1, 2, 3))))

show(**{"name": "Tom", "age": 18})


# ---------------------------------------------------------------------------
# 2. 函数定义时收集：*args 收成元组，**kwargs 收成字典
# ---------------------------------------------------------------------------

def collect(*args, **kwargs) -> None:
    print("   args   =", args, type(args).__name__)      # 元组
    print("   kwargs =", kwargs, type(kwargs).__name__)  # 字典


title("2. 定义时收集（打包）")

collect(1, 2, 3)
collect(a=1, b=2)
collect(1, 2, name="Tom", age=18)


# `*` 单独出现时是"分隔符"：它后面的参数只能按关键字传
def keyword_only(a, *, sep, end):
    print(f"   a={a} sep={sep!r} end={end!r}")


title("3. 单个 * 做分隔符 -> 强制关键字参数")
keyword_only(1, sep="-", end="!")
# keyword_only(1, "-", "!")   # 报错：sep/end 必须写名字


# ---------------------------------------------------------------------------
# 4. 字面量里解包：拼接列表 / 元组 / 集合 / 字典
# ---------------------------------------------------------------------------

title("4. 字面量里解包（拼接）")

a = [1, 2]
b = (3, 4)
c = {5, 6}
print("[*a, *b]     ->", [*a, *b])            # [1, 2, 3, 4]
print("(*b, *a)     ->", (*b, *a))            # (3, 4, 1, 2)
print("{*a, *c}     ->", {*a, *c})            # 集合去重
print("[0, *a, 99]  ->", [0, *a, 99])         # 前后都能加东西

d1 = {"x": 1, "y": 2}
d2 = {"y": 99, "z": 3}
print("{**d1, **d2} ->", {**d1, **d2})       # 后面的同名键覆盖前面 -> y 变成 99
print("{**d2, **d1} ->", {**d2, **d1})       # 反过来 -> y 变成 2

# 合并字典的现代写法（Python 3.9+ 的 | 运算符，效果一样）
print("d1 | d2      ->", d1 | d2)


# ---------------------------------------------------------------------------
# 5. 赋值时扩展解包：* 吃掉"剩下的"
# ---------------------------------------------------------------------------

title("5. 赋值时扩展解包")

first, *rest = [1, 2, 3, 4]
print("first, *rest      ->", first, rest)          # 1 [2, 3, 4]

first, *middle, last = (10, 20, 30, 40)
print("first,*mid,last   ->", first, middle, last)  # 10 [20, 30] 40

*init, last = "abcd"
print("*init, last       ->", init, last)           # ['a','b','c'] 'd'

# 解包元组时可以嵌套
(a1, a2), a3 = (1, 2), 3
print("嵌套解包          ->", a1, a2, a3)

# 交换变量其实也是解包（右边先打包成元组，再拆）
p, q = 1, 2
p, q = q, p
print("交换后            ->", p, q)


# ---------------------------------------------------------------------------
# 6. 常见坑
# ---------------------------------------------------------------------------

title("6. 常见坑")

# (a) 一个赋值里 * 只能出现一次
#     "多个 * 目标"是编译期错误，直接写会连整个文件都编译不过，
#     所以用 compile() 在运行时演示它被抓到的 SyntaxError。
try:
    compile("*x, *y = [1, 2, 3]", "<demo>", "exec")
except SyntaxError as e:
    print("多个 * 目标        -> SyntaxError:", e.msg)

# (b) ** 解的字典，键必须是字符串，且不能重复冲突
try:
    print({**{1: "a"}})                     # 字面量里这样其实允许非字符串键
    add3(**{"a": 1, "b": 2, "d": 3})        # d 不是形参名 -> TypeError
except TypeError as e:
    print("** 出现未知参数    -> TypeError:", e)

# (c) 位置参数不能出现在关键字参数后面
try:
    add3(a=1, *[2, 3])
except TypeError as e:
    print("a=1 后又用 *      -> TypeError:", e)

# (d) * 拆的是"可迭代对象"，整数不可迭代
try:
    add3(*5)
except TypeError as e:
    print("* 拆不可迭代对象   -> TypeError:", e)


if __name__ == "__main__":
    print("\n以上全部演示完毕。")
